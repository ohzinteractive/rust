import {registerHooks} from 'node:module';
import {test} from 'node:test';
import assert from 'node:assert/strict';
registerHooks({resolve(s,c,next){return next(s==='three'?new URL('../vendor/three.module.js',import.meta.url).href:s,c);}});
const THREE=await import('../vendor/three.module.js');
const {createDesertEnvironment}=await import('../desert-environment.js');

test('desert setting restores studio lighting, ground and fog across repeated toggles',()=>{
  const scene=new THREE.Scene(),background=new THREE.Color(0x141613),fog=new THREE.FogExp2(0x141613,.032);
  scene.background=background;scene.fog=fog;scene.environmentIntensity=.4;
  const ground=new THREE.Mesh(new THREE.PlaneGeometry(160,160),new THREE.MeshStandardMaterial({color:0x141a12})),studioMaterial=ground.material;
  const shadow=new THREE.Object3D(),skyLight=new THREE.HemisphereLight(0xe8f2e2,0x292218,1.1);
  const key=new THREE.DirectionalLight(0xfff0d8,3),rim=new THREE.DirectionalLight(0xbbe9df,1.25),fill=new THREE.DirectionalLight(0xffcf9d,.45);
  key.position.set(-3.5,6,4.5);
  const renderer={toneMappingExposure:.92,shadowMap:{needsUpdate:false,type:THREE.PCFSoftShadowMap},capabilities:{getMaxAnisotropy:()=>4}};
  const lights=[skyLight,key,rim,fill],original=lights.map(light=>({color:light.color.clone(),intensity:light.intensity,position:light.position.clone()})),groundColor=skyLight.groundColor.clone(),radius=key.shadow.radius;
  const setting=createDesertEnvironment({scene,renderer,ground,shadow,skyLight,key,rim,fill});
  setting.setEnabled(true);const sand=ground.material,sky=setting.sky;
  assert(setting.enabled&&sky.isSky&&sky.visible&&sand.map&&sand.bumpMap,'Daylight has a Sky dome and textured sand');
  assert.equal(scene.userData.skyToneMapped,true,'The mirage compositor tone maps the atmospheric sky');
  assert.equal(ground.scale.x,20,'The sand extends across the distant tower setting');
  assert.equal(shadow.visible,false);assert.equal(renderer.shadowMap.needsUpdate,true);
  assert.equal(renderer.shadowMap.type,THREE.PCFShadowMap);assert(key.shadow.radius<1,'Desert sunlight has a narrow shadow filter');
  const dunes=scene.getObjectByName('Distant desert dunes');assert(dunes?.visible,'The desert includes a distant dune layer');
  assert(key.intensity>skyLight.intensity*4,'Direct sun dominates the ambient fill');
  const originalDirection=setting.sunDirection;
  setting.setSunSettings({elevation:28,azimuth:240});
  const direction=key.position.clone().sub(key.target.position).normalize();
  assert(direction.distanceTo(setting.sunDirection)<1e-10,'Shadow casting sunlight follows the requested position');
  assert(direction.distanceTo(sky.material.uniforms.sunPosition.value)<1e-10,'The sky and shadow light share one sun direction');
  assert(direction.distanceTo(originalDirection)>.1,'Moving the sun changes its actual direction');
  const towerBounds=new THREE.Box3(new THREE.Vector3(-480,-1.75,-320),new THREE.Vector3(-450,198.25,-296));
  setting.setShadowBounds(towerBounds);assert(key.target.position.x< -400&&key.shadow.camera.far>200,'Building view covers the distant tower shadow');
  setting.setShadowBounds(null);assert.deepEqual(key.target.position,new THREE.Vector3());assert.equal(key.shadow.camera.far,80,'Oasis view restores its focused shadow map');
  setting.setShadowBounds(towerBounds);
  setting.setEnabled(true);setting.setEnabled(false);
  assert.equal(scene.background,background);assert.equal(scene.fog,fog);assert.equal(ground.material,studioMaterial);
  assert.deepEqual(ground.scale,new THREE.Vector3(1,1,1));
  assert.equal(scene.environmentIntensity,.4);assert.equal(shadow.visible,true);assert.equal(key.shadow.radius,radius);
  assert.equal(renderer.shadowMap.type,THREE.PCFSoftShadowMap,'The studio shadow filter is restored');
  assert.equal(dunes.visible,false,'Distant scenery is hidden outside the desert');
  assert.equal(sky.visible,false);assert.equal(scene.userData.skyToneMapped,undefined);
  assert.deepEqual(key.target.position,new THREE.Vector3());assert.equal(key.shadow.bias,0,'Studio restores the original shadow target and bias');
  assert.deepEqual(skyLight.groundColor,groundColor);
  lights.forEach((light,i)=>{assert.equal(light.intensity,original[i].intensity);assert.deepEqual(light.color,original[i].color);assert.deepEqual(light.position,original[i].position);});
  setting.setEnabled(true);assert.equal(ground.material,sand);assert.equal(setting.sky,sky,'Switching reuses sky and sand resources');
  assert.deepEqual(setting.sunSettings,{elevation:28,azimuth:240},'Sun preferences survive environment switches');
  assert(key.position.clone().normalize().distanceTo(direction)<1e-10);
  let disposed=0;sand.map.addEventListener('dispose',()=>disposed++);setting.dispose();
  assert.equal(disposed,1);assert.equal(ground.material,studioMaterial);ground.geometry.dispose();studioMaterial.dispose();
  assert.equal(scene.getObjectByName('Distant desert dunes'),undefined,'Disposal releases the distant scenery');
});
